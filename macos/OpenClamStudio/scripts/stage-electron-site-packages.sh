#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PYTHON="$ROOT/.electron-python-runtime/bin/python"
LOCK="$ROOT/requirements-electron.lock"
OUT="$ROOT/.electron-site-packages"

if [[ "$(uname -m)" != "arm64" ]]; then
  echo "Electron dependencies are locked for Apple Silicon" >&2
  exit 1
fi
if [[ "$(sw_vers -productVersion | cut -d. -f1)" -lt 14 ]]; then
  echo "macOS 14 or newer is required" >&2
  exit 1
fi
if [[ ! -x "$PYTHON" || ! -f "$LOCK" ]]; then
  echo "stage the Python runtime and generate requirements-electron.lock first" >&2
  exit 1
fi
if ! command -v uv >/dev/null 2>&1; then
  echo "uv is required to stage the Electron dependency set" >&2
  exit 1
fi

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
PYTHONDONTWRITEBYTECODE=1 uv venv --python "$PYTHON" "$WORK/venv" >/dev/null
PYTHONDONTWRITEBYTECODE=1 uv pip sync \
  --python "$WORK/venv/bin/python" --require-hashes "$LOCK"

rm -rf "$OUT"
ditto "$WORK/venv/lib/python3.12/site-packages" "$OUT"
find "$OUT" -type d \( -name __pycache__ -o -name tests -o -name test \) -prune -exec rm -rf {} +
find "$OUT" -type f \( -name '*.pyc' -o -name '.DS_Store' \) -delete
rm -rf "$OUT/torch" "$OUT/functorch" "$OUT/torchgen" "$OUT/isympy.py" \
  "$OUT"/torch-*.dist-info "$OUT/mlx/include"
xattr -cr "$OUT" 2>/dev/null || true

"$ROOT/scripts/stage-electron-opencv.sh" "$OUT"
PYTHONDONTWRITEBYTECODE=1 "$PYTHON" -B \
  "$ROOT/scripts/audit-electron-dependencies.py" "$OUT"
PYTHONDONTWRITEBYTECODE=1 "$PYTHON" -B \
  "$ROOT/scripts/audit-macos-deployment-targets.py" \
  "$ROOT/.electron-python-runtime" "$OUT" --max 14.0

OPENCLAM_NO_RVM=1 PYTHONPATH="$OUT" "$PYTHON" -B - <<'PY'
import cv2, edge_tts, fastapi, httpx, mediapipe, mlx_whisper, numpy, scipy, soundfile, uvicorn
try:
    import torch
except ModuleNotFoundError:
    pass
else:
    raise AssertionError("PyTorch must not be redistributed in the Electron app")
try:
    import kokoro
except ModuleNotFoundError:
    pass
else:
    raise AssertionError("Kokoro must not be redistributed in the Electron app")
print("staged GPL-free Electron dependencies")
PY

# Some third-party imports create bytecode despite the initial wheel cleanup.
# Generated bytecode can retain build-machine paths, so release staging always
# removes it after the final smoke test and then scans the stable payload.
find "$OUT" -type d -name __pycache__ -prune -exec /bin/rm -rf {} +
find "$OUT" -type f \( -name '*.pyc' -o -name '.DS_Store' \) -delete
if /usr/bin/grep -R -a -l -F -- "$HOME" "$OUT" >"$WORK/private-path-matches"; then
  echo "private home path remains in Electron dependencies" >&2
  exit 1
else
  scan_status=$?
  if [[ $scan_status -ne 1 ]]; then
    echo "could not complete the Electron dependency private-path scan" >&2
    exit 1
  fi
fi

# uv and dependency audits may start the base interpreter. Keep this standalone
# staging command safe as well as the final stage:backend packaging boundary.
"$ROOT/scripts/stage-electron-python.sh" --scrub-only
